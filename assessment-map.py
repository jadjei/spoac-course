#!/usr/bin/env python3
"""Generate the assessment-to-learning-target map.

Milestone 3's evidence requirement asks for "documentation linking assessment tools to
specific learning objectives". That link already exists in the files — each assignment
carries an `assesses:` list of the SLT indices it evidences — so the map is generated,
never hand-maintained, and cannot drift from what is actually on the platform.

SLT text comes from `import-staging/<code>/outline.md`, which is the exact payload sent to
Andamio, so the numbering matches the live module.

Usage: python3 assessment-map.py            # writes plan/assessment-map.md
"""
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "plan", "assessment-map.md")
COURSE_ID = "e60f29abf7a3f348bf4f51a078dae6f53cd3bc065d74632d3f67d785"


def frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    fm = {}
    if m:
        for line in m.group(1).splitlines():
            mm = re.match(r'(\w+):\s*(.*)', line)
            if mm:
                fm[mm.group(1)] = mm.group(2).strip().strip('"')
    return fm


def slts_for(code):
    path = os.path.join(HERE, "import-staging", code, "outline.md")
    if not os.path.exists(path):
        return []
    body = open(path).read()
    return [re.sub(r"^\d+\.\s*", "", l).strip()
            for l in body.splitlines() if re.match(r"^\d+\.\s", l)]


def main():
    rows, missing = [], []
    for d in sorted(glob.glob(os.path.join(HERE, "course", "*/"))):
        module = os.path.basename(d.rstrip("/"))
        code = module.split("-")[0]
        assigns = sorted(glob.glob(os.path.join(d, "*.assignment.md")))
        authored = []
        for f in assigns:
            t = open(f).read()
            fm = frontmatter(t)
            if "TODO:" in t:
                continue
            authored.append((fm, f))
        if not authored:
            missing.append(code)
            continue
        fm, path = authored[-1]           # module capstone — the one convert.py ships
        slts = slts_for(code)
        idx = [int(n) for n in re.findall(r"\d+", fm.get("assesses", ""))]
        rows.append(dict(code=code, title=fm.get("title", "?"), file=os.path.relpath(path, HERE),
                         slts=slts, idx=idx))

    lines = [
        "# Assessment map — which assignment evidences which learning target",
        "",
        "GENERATED by `assessment-map.py` — do not hand-edit; edit the `assesses:` list in the",
        "assignment file and re-run.",
        "",
        "Andamio holds **one assignment per module**, so each module's assignment is its",
        "capstone: it must evidence that module's Student Learning Targets between them. SLT",
        "numbering matches the live module — the text below is taken from the exact payload",
        "sent to the platform.",
        "",
        f"Live course: `{COURSE_ID}`",
        "",
    ]
    total_slts = total_covered = 0
    for r in rows:
        lines += [f"## Module {r['code']} — {r['title']}", "",
                  f"Source: `{r['file']}`", "",
                  "| SLT | Learning target | Evidenced |", "|---|---|---|"]
        for i, s in enumerate(r["slts"], 1):
            hit = "yes" if i in r["idx"] else "—"
            lines.append(f"| {i} | {s} | {hit} |")
        covered = len([i for i in r["idx"] if i <= len(r["slts"])])
        total_slts += len(r["slts"])
        total_covered += covered
        lines += ["", f"Covers {covered} of {len(r['slts'])} targets.", ""]

    pct = (100 * total_covered / total_slts) if total_slts else 0
    lines[5:5] = [f"**{len(rows)} modules carry an assignment. "
                  f"{total_covered} of {total_slts} learning targets ({pct:.0f}%) are directly "
                  f"evidenced by one.**", ""]
    if missing:
        lines += ["## Modules with no authored assignment", "",
                  ", ".join(missing) or "none", ""]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"{len(rows)} modules mapped, {total_covered}/{total_slts} targets evidenced "
          f"({pct:.0f}%) → {os.path.relpath(OUT, HERE)}")
    if missing:
        print(f"no assignment: {', '.join(missing)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
