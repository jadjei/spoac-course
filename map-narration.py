#!/usr/bin/env python3
"""Map deck narration into the course elements it belongs to.

For every element in plan/course-plan.yaml carrying a deck (`source: spo`, or
`general` where no SPO deck exists), write that deck's speaker-note narration into the
element's `## Content` section, slide by slide. The planner still owns everything above
it — title, Overview, Student Learning Targets — which is left untouched.

This is a transfer, not a rewrite. The narration is Harry's approved script and reads as
finished prose; slide titles become subheadings, and slides carrying a diagram get a
figure reference. Nothing is summarised, reordered, or invented.

Figures point at `assets/<code>-slide-N.svg`. Those files are produced separately (see
decks-to-svg.py and the diagram-extraction pass) — this script reports any that are
missing rather than silently emitting dead links.

Usage:
    python3 map-narration.py --dry-run          # report coverage, write nothing
    python3 map-narration.py                    # write all
    python3 map-narration.py --code 501         # one element
"""
import argparse, datetime, glob, os, re, sys
import yaml
from pptx import Presentation
from pptx.enum.shapes import MSO_SHAPE_TYPE

HERE = os.path.dirname(os.path.abspath(__file__))
PLAN = os.path.join(HERE, "plan", "course-plan.yaml")
COURSE = os.path.join(HERE, "course")
DL = os.path.join(HERE, "spoac-dl")

BOILERPLATE = re.compile(
    r"^\s*(IP\s*FOUNDARY|©\s*Edify.*|Generated by Copilot|SPOAcademy|"
    r"Stake Pool Operator Academy|[\d.]+\s*[·.]\s*\d+\s*/\s*\d+|\d{1,3})\s*$", re.I)

DIAGRAM_TYPES = {MSO_SHAPE_TYPE.PICTURE, MSO_SHAPE_TYPE.GROUP, MSO_SHAPE_TYPE.FREEFORM,
                 MSO_SHAPE_TYPE.CHART, MSO_SHAPE_TYPE.TABLE}


def clean(text):
    out = []
    for ln in (text or "").splitlines():
        s = ln.strip()
        if s and not BOILERPLATE.match(s):
            out.append(s)
    return out


def slide_heading(slide):
    """The slide's title, minus the deck-wide prefix most decks repeat on every slide."""
    t = slide.shapes.title
    raw = (t.text if t is not None else "") or ""
    lines = [l.strip() for l in raw.splitlines() if l.strip()]
    if not lines:
        return ""
    head = lines[-1]                      # 'Organisation Biome\nRevenue: Marketing'
    head = re.sub(r"^\s*\d[\d.]*\s+", "", head)   # a leading element code
    return head.strip()


def has_diagram(slide):
    autoshapes = 0
    for sh in slide.shapes:
        try:
            st = sh.shape_type
        except Exception:
            continue
        if st in DIAGRAM_TYPES:
            return True
        if st == MSO_SHAPE_TYPE.AUTO_SHAPE:
            autoshapes += 1
    return autoshapes >= 4      # a cluster of shapes is a diagram; one or two is decor


def deck_for(el):
    decks = el.get("spo_decks") or el.get("general_decks") or []
    for d in decks:
        if d.lower().endswith(".pptx"):
            return d
    return None


def build_body(deck_rel, code, asset_dir):
    deck_abs = os.path.join(HERE, deck_rel)
    prs = Presentation(deck_abs)
    name = os.path.basename(deck_rel)
    # rclone preserves the Drive modified time, so the local mtime dates the deck itself —
    # a truer staleness marker than the pull date, and never hardcoded
    modified = datetime.date.fromtimestamp(os.path.getmtime(deck_abs)).isoformat()
    out = [f"_Lesson body from the speaker-note narration of `{name}`, slide by slide "
           f"(deck modified {modified}). Planner owns the Overview and SLTs above._", ""]
    missing, figures, words = [], 0, 0

    for n, slide in enumerate(prs.slides, 1):
        notes = []
        if slide.has_notes_slide:
            notes = clean(slide.notes_slide.notes_text_frame.text)
        if not notes:
            continue
        head = slide_heading(slide)
        if n > 1 and head:
            out += [f"### {head}", ""]
        for para in notes:
            out += [para, ""]
            words += len(para.split())
        if has_diagram(slide):
            # extract-diagrams.py writes vector figures as .svg and picture-only
            # figures in their original raster format — reference whichever exists
            stem = f"{code}-slide-{n}"
            # raster first: Andamio's CDN rejects SVG (INVALID_TYPE), so a lesson that
            # references the .svg master ships a broken image. The SVG stays on disk as
            # the themable source; extract-diagrams.py writes a .png beside it.
            found = next((f"{stem}{e}" for e in (".png", ".jpg", ".jpeg", ".svg", ".emf")
                          if os.path.exists(os.path.join(asset_dir, f"{stem}{e}"))), None)
            if not found:
                missing.append(f"{stem}.svg")
                found = f"{stem}.svg"
            out += [f"![{head or f'Slide {n}'}](assets/{found})", ""]
            figures += 1

    return "\n".join(out).rstrip() + "\n", words, figures, missing


def splice(text, body):
    """Replace the ## Content / ## Assignment section, keeping everything above it."""
    m = re.search(r"\n## (Content|Assignment)\b", text)
    if not m:
        return text.rstrip() + "\n\n## Content\n\n" + body
    return text[:m.start()].rstrip() + f"\n\n## {m.group(1)}\n\n" + body


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--code", action="append", help="only this element code (repeatable)")
    ap.add_argument("--plan", default=PLAN,
                    help="plan to read decks from (default plan/course-plan.yaml)")
    args = ap.parse_args()

    plan = yaml.safe_load(open(args.plan))
    files = {}
    for f in glob.glob(os.path.join(COURSE, "*", "*.md")):
        m = re.search(r'^code:\s*"([^"]+)"', open(f).read(), re.M)
        if m:
            files[m.group(1)] = f

    done = skipped = 0
    tot_words = tot_figs = 0
    all_missing = []
    for mod in plan["modules"]:
        for el in mod["elements"]:
            code = str(el["code"])
            if args.code and code not in args.code:
                continue
            deck = deck_for(el)
            if not deck or code not in files:
                skipped += 1
                continue
            path = files[code]
            asset_dir = os.path.join(os.path.dirname(path), "assets")
            body, words, figs, missing = build_body(deck, code, asset_dir)
            if not words:
                skipped += 1
                continue
            tot_words += words
            tot_figs += figs
            all_missing += [(code, m) for m in missing]
            if not args.dry_run:
                # read fully before opening for write: open(...,"w") truncates, so
                # reading inside the write call yields an empty file
                current = open(path).read()
                open(path, "w").write(splice(current, body))
            print(f"  {code:7} {words:5} words  {figs} figures  <- {os.path.basename(deck)[:44]}")
            done += 1

    print(f"\n{done} elements mapped ({tot_words:,} words, {tot_figs} figures); {skipped} skipped")
    if all_missing:
        print(f"{len(all_missing)} figure files not yet generated "
              f"(diagram-extraction pass owes them):")
        for code, m in all_missing[:8]:
            print(f"    {code}: assets/{m}")
        if len(all_missing) > 8:
            print(f"    … and {len(all_missing) - 8} more")
    if args.dry_run:
        print("\nDRY RUN — nothing written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
