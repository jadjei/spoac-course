#!/usr/bin/env python3
"""Extract text + images from the SPO Academy .pptx decks into an `extracted/` mirror.

Mechanical, deterministic, no judgment: walk a locally-downloaded copy of the Drive
course folder, and for every .pptx write a markdown file mirroring its path under
`extracted/`, plus its images under `extracted/.../assets/`. A second (manual /
per-module) pass maps this into the `course/` scaffold.

Per slide it captures: the slide's text (title + body) and — most importantly — the
**speaker notes / narrative**, which are the lesson body. Common Edify boilerplate
is stripped.

Usage:
    python3 extract.py --src ~/Downloads/<downloaded-course-folder>
    # then read extracted/INDEX.md

Requires: python-pptx, Pillow (both already installed).
"""
import argparse, hashlib, os, re, sys

try:
    from pptx import Presentation
    from pptx.util import Emu  # noqa: F401
except ImportError:
    sys.exit("python-pptx not installed: pip install python-pptx")

HERE = os.path.dirname(os.path.abspath(__file__))

BOILERPLATE = re.compile(
    r"^\s*(IP\s*FOUNDARY|©\s*Edify.*|Generated by Copilot|SPOAcademy|\d{1,3})\s*$",
    re.I,
)


def clean_lines(text):
    out = []
    for ln in (text or "").splitlines():
        s = ln.strip()
        if not s or BOILERPLATE.match(s):
            continue
        out.append(s)
    return out


def slide_title(slide):
    if slide.shapes.title and (slide.shapes.title.text or "").strip():
        return slide.shapes.title.text.strip()
    return ""


def slide_body(slide, skip_title):
    parts = []
    for sh in slide.shapes:
        if not sh.has_text_frame:
            continue
        t = (sh.text_frame.text or "").strip()
        if t and t != skip_title:
            parts.append(t)
    return clean_lines("\n".join(parts))


def slide_notes(slide):
    if not slide.has_notes_slide:
        return []
    return clean_lines(slide.notes_slide.notes_text_frame.text)


def save_images(slide, n, assets_dir, seen):
    refs = []
    for sh in slide.shapes:
        try:
            img = sh.image  # raises on non-picture shapes
        except (AttributeError, ValueError, KeyError, TypeError):
            continue
        digest = hashlib.sha1(img.blob).hexdigest()[:10]
        if digest in seen:
            refs.append(seen[digest])
            continue
        os.makedirs(assets_dir, exist_ok=True)
        fname = f"slide{n}-{digest}.{img.ext}"
        with open(os.path.join(assets_dir, fname), "wb") as f:
            f.write(img.blob)
        rel = f"assets/{fname}"
        seen[digest] = rel
        refs.append(rel)
    return refs


def extract_deck(pptx_path, out_md, assets_dir):
    prs = Presentation(pptx_path)
    seen = {}
    n_slides = len(prs.slides._sldIdLst)
    md = [f"# {os.path.basename(pptx_path)}", "",
          f"_Extracted from `{pptx_path}` — {n_slides} slides._", ""]
    n_imgs = 0
    for i, slide in enumerate(prs.slides, 1):
        title = slide_title(slide)
        body = slide_body(slide, title)
        notes = slide_notes(slide)
        imgs = save_images(slide, i, assets_dir, seen)
        n_imgs += len([x for x in imgs if x])
        md.append(f"## Slide {i}" + (f" — {title}" if title else ""))
        md.append("")
        if notes:
            md += ["**Narrative / speaker notes:**", "", *[f"{l}" for l in notes], ""]
        if body:
            md += ["**Slide text:**", "", *[f"- {l}" for l in body], ""]
        for r in imgs:
            md.append(f"![slide {i}]({r})")
        if imgs:
            md.append("")
    open(out_md, "w").write("\n".join(md))
    return len(prs.slides._sldIdLst), len(seen)


def pick_decks(folder):
    """Return the .pptx files in a folder (all of them — version choice is left to the
    mapping pass; we extract everything so nothing is missed)."""
    return sorted(f for f in os.listdir(folder)
                  if f.lower().endswith(".pptx") and not f.startswith("~$"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, help="Local downloaded course folder root")
    ap.add_argument("--out", default=os.path.join(HERE, "extracted"))
    args = ap.parse_args()
    src = os.path.expanduser(args.src)
    if not os.path.isdir(src):
        sys.exit(f"not a directory: {src}")

    index = ["# Extracted decks", "", f"Source: `{src}`", "",
             "| deck | slides | images | extracted md |", "|---|---|---|---|"]
    total = 0
    for root, _dirs, files in os.walk(src):
        for f in sorted(files):
            if not f.lower().endswith(".pptx") or f.startswith("~$"):
                continue
            pptx_path = os.path.join(root, f)
            rel = os.path.relpath(pptx_path, src)
            out_md = os.path.join(args.out, rel + ".md")
            assets = os.path.join(os.path.dirname(out_md), "assets")
            os.makedirs(os.path.dirname(out_md), exist_ok=True)
            try:
                ns, ni = extract_deck(pptx_path, out_md, assets)
                index.append(f"| {rel} | {ns} | {ni} | {os.path.relpath(out_md, args.out)} |")
                total += 1
                print(f"  ✓ {rel}  ({ns} slides, {ni} images)")
            except Exception as e:  # noqa: BLE001
                index.append(f"| {rel} | ERROR | — | {type(e).__name__}: {e} |")
                print(f"  ✗ {rel}  {type(e).__name__}: {e}")
    os.makedirs(args.out, exist_ok=True)
    open(os.path.join(args.out, "INDEX.md"), "w").write("\n".join(index) + "\n")
    print(f"\nExtracted {total} decks → {args.out}  (see INDEX.md)")


if __name__ == "__main__":
    main()
